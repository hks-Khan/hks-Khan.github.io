function detailEmphasis(text: string = "") {
  return text.split("\n\n").flatMap((paragraph, index) => {
    const phrase = DETAIL_EMPHASIS.find((candidate) => paragraph.includes(candidate));
    const separator = index ? "\n\n" : "";
    if (!phrase) return [separator, paragraph];
    const start = paragraph.indexOf(phrase);
    return [separator, paragraph.slice(0, start),
      <strong key={index} className="px-0.5 font-medium text-[#424245] [box-decoration-break:clone]">{phrase}</strong>,
      paragraph.slice(start + phrase.length)];
  });
}


function ArticleBody({ text }: { text: string }) {
  const inline = (value: string) => value.split(/(\*\*.*?\*\*|`[^`]+`)/g).map((part, i) =>
    part.startsWith("**") ? <strong key={i} className="font-medium text-[#242426]">{part.slice(2, -2)}</strong>
      : part.startsWith("`") ? <span key={i}>{part.slice(1, -1)}</span> : part);
  return <div className="space-y-5 break-keep text-[16px] font-normal leading-[1.9] text-[#424245]">
    {text.split(/\n\s*\n/).map((block, i) => {
      if (/^#{3,4} /.test(block)) return <h5 key={i} className="pt-5 text-[18px] font-semibold leading-relaxed text-[#242426]">{block.replace(/^#{3,4} /, "")}</h5>;
      if (/^[-\d]/.test(block) && /^(?:- |\d+\. )/.test(block)) {
        const items = block.split("\n").map((line, j) => <li key={j}>{inline(line.replace(/^(?:- |\d+\. )/, ""))}</li>);
        return block.startsWith("- ") ? <ul key={i} className="list-disc space-y-3 pl-5">{items}</ul> : <ol key={i} className="list-decimal space-y-3 pl-5">{items}</ol>;
      }
      return <p key={i}>{inline(block)}</p>;
    })}
  </div>;
}

